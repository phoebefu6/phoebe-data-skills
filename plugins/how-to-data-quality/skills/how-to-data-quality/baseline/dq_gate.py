# ----------------------------------------------------------------- main
def main() -> None:
    preflight()
    OUT.mkdir(exist_ok=True)
    frames = load_raw()

    before, extras = run_gate(frames)
    s_before = score(before)
    print(f"FAIL run: verdict {s_before['verdict']}, score {s_before['overall']}")
    for r in before:
        flag = "PASS" if r.passed else f"{r.severity} {r.error_rate:.2%}"
        print(f"  [{flag:>14}] {r.dimension:12} {r.check}")

    fixed, ledger = apply_fixes(frames, extras)
    # apply_fixes already conformed the merchant master's key via its own
    # legacy_id crosswalk - the PASS run re-checks the same semantics on the
    # frames exactly as they will load
    after, extras_after = run_gate(
        {
            "transactions": fixed["transactions"],
            "payments": fixed["payments"].drop(columns=["finance_hold"]),
            "products": fixed["products"],
            "merchants": fixed["merchants"],
        }
    )
    # the heaping merchant is known and HELD - the PASS run's accuracy check
    # re-flags it by design and its error rate stays in the score; only the
    # detail string is annotated so the artifacts say where the rows went
    for r in after:
        if r.dimension == "accuracy" and not r.passed:
            r.detail += " [payments on finance_hold - resolved by routing, not editing]"
    s_after = score(after)
    print(f"PASS run: verdict {s_after['verdict']}, score {s_after['overall']}")

    # the money block - what the bad data was about to cost, computed
    tx_raw = frames["transactions"]
    q_ids = set(
        ledger[(ledger.table == "transactions") & (ledger.action == "quarantined")][
            "row_id"
        ]
    )
    q_lines = tx_raw[tx_raw.txn_id.isin(q_ids)]
    gmv_quarantined = float(
        (q_lines.qty * q_lines.unit_price * (1 - q_lines.discount)).sum()
    )
    held_refs = set(
        ledger[(ledger.table == "payments") & (ledger.action == "finance_hold")][
            "row_id"
        ]
    )
    pay_raw = frames["payments"]
    amount_on_hold = float(
        pay_raw[pay_raw.pmt_ref.isin(held_refs)].amount_reported.sum()
    )
    ids_merged = int((ledger.action == "merged").sum())
    observable_customers = int(
        tx_raw.dropna(subset=["cust_signup_ts"]).customer_id.nunique()
    )
    shifted = int((ledger.action == "corrected").sum())
    money = {
        "gmv_quarantined": gmv_quarantined,
        "amount_on_hold": amount_on_hold,
        "ids_merged": ids_merged,
        "buyer_overstatement_pct": ids_merged / observable_customers * 100,
        "tz_shift_hours": TZ_OFFSET_HOURS,
        "payments_shifted_pct": shifted / len(pay_raw) * 100,
    }

    chart_dimension_matrix(before, after)
    chart_referential(before)
    chart_categories(frames)
    lat_before = extras["latency_hours"]
    lat_after = extras_after["latency_hours"]
    chart_latency(lat_before, lat_after)
    chart_heaping(extras["heaping"])
    chart_funnel(frames, fixed, ledger)

    ledger.to_csv(OUT / "quarantine_ledger.csv", index=False)
    build_scorecard(before, after, s_before, s_after, ledger, frames, fixed, money)
    write_findings(before, after, s_before, s_after, ledger, frames, fixed, money)

    results = {
        "seed": SEED,
        "raw_files": {k: len(v) for k, v in load_raw().items()},
        "fail_run": {"score": s_before, "checks": [r.to_dict() for r in before]},
        "pass_run": {"score": s_after, "checks": [r.to_dict() for r in after]},
        "ledger_actions": ledger.action.value_counts().to_dict(),
        "tx_loaded": len(fixed["transactions"]),
        "payments_loaded": len(fixed["payments"]),
        "identities_merged_into": fixed["survivor_count"],
        "tz_regions_diagnosed": fixed["tz_regions"],
        "evidence_sha256": fixed["evidence_sha256"],
        "money": money,
    }
    (OUT / "dq_results.json").write_text(json.dumps(results, indent=2, default=str))
    tx_in, pay_in = len(frames["transactions"]), len(frames["payments"])
    q_pay = int(((ledger.table == "payments") & (ledger.action == "quarantined")).sum())
    q_tx = int(
        ((ledger.table == "transactions") & (ledger.action == "quarantined")).sum()
    )
    print(
        f"reconciliation: tx {tx_in:,} = {len(fixed['transactions']):,} loaded "
        f"+ {q_tx:,} quarantined | payments {pay_in:,} = "
        f"{len(fixed['payments']):,} loaded + {q_pay:,} quarantined"
    )
    print(f"\noutputs written to {OUT}")


if __name__ == "__main__":
    main()
