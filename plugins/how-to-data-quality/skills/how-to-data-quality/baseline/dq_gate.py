"""Everrest data-quality gate - Analytics layer (validation + scorecard track).

DECISION: does Monday's warehouse load ship, or is it blocked - and on what
evidence? Not "run some checks": a gate with a verdict, a quarantine ledger, and
a board-facing scorecard where every number is computed, never typed.

THE SETUP. The Everrest raw dump (stage 0 of the lineage, seed 42) carries six
planted ingestion defects, documented in the generator's docstring
(../how-to-schema-and-warehouse/generate_raw.py). Each maps onto one of the six
classic data-quality dimensions, so the gate is a complete tour of the
discipline on data where the ground truth is known:

  defect in raw                          dimension       gate check
  1 orphan foreign keys (~2.5% / ~1%) -> consistency     referential integrity
  2 14 category label variants        -> validity        accepted-values
  3 MER-0001 vs M0001 key formats     -> consistency     cross-system conformity
  4 PH payments logged local UTC+8    -> timeliness      event-order (paid >= order)
  5 M0333 round-hundred amounts       -> accuracy        heaping / fabrication scan
  6 ~800 customers under two ids      -> uniqueness      duplicate-identity scan
  (completeness rides on 1: orphan customer refs surface as null attributes)

WHAT THE GATE DOES, IN ORDER
  1. preflight  - the four raw files exist and carry the expected columns; fail
                  loudly with the exact path and missing column if not.
  2. FAIL run   - pandera schemas + four custom scans on the raw dump. The load
                  is BLOCKED: every defect above trips its check, and the run
                  writes the evidence (counts, offending samples, per-table
                  error rates).
  3. fixes      - the ingestion transforms a real pipeline would apply:
                  quarantine orphan lines, map the 14 labels to 8 canon
                  categories, normalize merchant keys, shift PH paid_at to UTC,
                  merge duplicate identities (earliest id survives), and route
                  M0333 to investigation (fabrication is EXCLUDED from finance
                  rollups, not silently "fixed" - a defect in the world is not a
                  defect you can transform away).
  4. PASS run   - the same checks re-run on the fixed tables and pass; the
                  quarantine ledger reconciles every row: rows_in = rows_loaded
                  + rows_quarantined + rows_merged, per table.
  5. artifacts  - dq_results.json (every computed value), findings.md (the
                  memo), 7 charts, and everrest_dq_scorecard.html - a
                  self-contained scorecard whose every figure is injected from
                  dq_results.json.

HONESTY GATES
  - The FAIL run is real: the checks genuinely trip on the raw files; nothing is
    mocked. The PASS run re-executes the same check functions on the fixed
    frames.
  - Scorecard numbers are computed-not-typed: the HTML is generated by this
    script from the results dict; grep it for a hand-written digit and you will
    not find one.
  - The M0333 heaping is flagged, quantified, and routed - not repaired. A DQ
    tool that "fixes" fabricated amounts is lying twice.
  - Scores follow one stated formula (below); the scorecard shows the formula.

SCORING (stated so the card is auditable)
  check error_rate = offending rows / rows checked, on the check's own grain.
  dimension score  = 100 x (1 - error_rate), worst check wins the dimension
                     (a dimension is as good as its worst defect).
  overall          = mean of the six dimension scores; the VERDICT is not the
                     score - the gate blocks on any BLOCKER-severity failure
                     regardless of how pretty the average is.

Marts and raw were generated with seed 42 (see how-to-schema-and-warehouse).
This script is read-only on the raw files; fixed tables live in memory and the
quarantine ledger is written to output/.

Run (from this folder):
    python dq_gate.py
Outputs -> ./output/ :
    dq_results.json                every computed value
    quarantine_ledger.csv          every quarantined/merged row, with reason
    findings.md                    the written gate memo
    everrest_dq_scorecard.html     the self-contained DQ scorecard
    evidence/                      as-received snapshot of held payments + sha256
    dq_dimension_matrix.png        every check's error rate, before vs after
    referential_orphans.png        the two orphan populations, sized
    category_variants.png          14 raw labels collapsing to 8 canon
    latency_histogram.png          order-to-paid hours; the impossible block
    heaping_m0333.png              round-hundred heaping vs the peer rate
    gate_funnel.png                lines in -> quarantined -> loaded, linear
"""

