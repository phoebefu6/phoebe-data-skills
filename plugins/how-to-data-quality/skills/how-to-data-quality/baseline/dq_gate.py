# ----------------------------------------------------------------- check result
@dataclass
class CheckResult:
    check: str
    dimension: str
    table: str
    severity: str  # BLOCKER or WARN
    rows_checked: int
    rows_failed: int
    detail: str
    owner: str = "data engineering"  # the accountable steward, not just a table
    sample: list = field(default_factory=list)

    @property
    def error_rate(self) -> float:
        return self.rows_failed / self.rows_checked if self.rows_checked else 0.0

    @property
    def passed(self) -> bool:
        return self.rows_failed == 0

    def to_dict(self) -> dict:
        return {
            "check": self.check,
            "dimension": self.dimension,
            "table": self.table,
            "severity": self.severity,
            "rows_checked": self.rows_checked,
            "rows_failed": self.rows_failed,
            "error_rate_pct": round(self.error_rate * 100, 3),
            "passed": self.passed,
            "detail": self.detail,
            "owner": self.owner,
            "sample": self.sample[:5],
        }


# ----------------------------------------------------------------- preflight
def preflight() -> None:
    """Fail loudly, with the exact path and column, before any check runs."""
    expected = {
        "raw_transactions.csv": {
            "txn_id",
            "order_id",
            "order_ts_utc",
            "status",
            "customer_id",
            "cust_signup_ts",
            "cust_channel",
            "cust_region",
            "merchant_id",
            "category_raw",
            "product_id",
            "qty",
            "unit_price",
            "discount",
        },
        "raw_payments_export.csv": {
            "pmt_ref",
            "order_id",
            "method",
            "amount_reported",
            "paid_at",
        },
        "raw_products_export.csv": {"product_id", "merchant_id", "catalog_price"},
    }
    if not RAW.exists():
        raise SystemExit(
            f"raw dump not found at {RAW} - run generate_raw.py in "
            f"{RAW.parent} first (stage 0 of the Everrest lineage)"
        )
    for fname, cols in expected.items():
        f = RAW / fname
        if not f.exists():
            raise SystemExit(f"missing raw file: {f}")
        have = set(pd.read_csv(f, nrows=0).columns)
        missing = cols - have
        if missing:
            raise SystemExit(
                f"{fname} is missing expected columns {sorted(missing)} - "
                "point RAW at an Everrest-shaped dump or adapt the schemas below"
            )
    if not (RAW / "raw_merchants_extract.json").exists():
        raise SystemExit(f"missing raw file: {RAW / 'raw_merchants_extract.json'}")


# ----------------------------------------------------------------- load
def load_raw() -> dict[str, pd.DataFrame]:
    tx = pd.read_csv(
        RAW / "raw_transactions.csv",
        parse_dates=["order_ts_utc", "cust_signup_ts"],
        date_format="ISO8601",
    )
    pay = pd.read_csv(
        RAW / "raw_payments_export.csv", parse_dates=["paid_at"], date_format="ISO8601"
    )
    prod = pd.read_csv(RAW / "raw_products_export.csv")
    mer = pd.DataFrame(json.load(open(RAW / "raw_merchants_extract.json")))
    return {"transactions": tx, "payments": pay, "products": prod, "merchants": mer}


# ----------------------------------------------------------------- checks
def check_structural(frames: dict[str, pd.DataFrame]) -> list[CheckResult]:
    """Pandera structural schemas: types, nulls, ranges. The table stakes."""
    results: list[CheckResult] = []
    tx_schema = pa.DataFrameSchema(
        {
            "txn_id": pa.Column(str, nullable=False),
            "order_id": pa.Column(str, nullable=False),
            "qty": pa.Column(int, pa.Check.ge(1)),
            "unit_price": pa.Column(float, pa.Check.gt(0)),
            "discount": pa.Column(float, pa.Check.in_range(0.0, 0.9)),
        },
        strict=False,
    )
    tx = frames["transactions"]
    try:
        tx_schema.validate(tx, lazy=True)
        failed = 0
        detail = "types, ranges and keys all conform"
        sample: list = []
    except pa.errors.SchemaErrors as e:
        # count failing ROWS, not failure cases - a row failing two checks is
        # still one bad row, and cases-per-row > 1 would push error_rate past 1
        failed = int(e.failure_cases["index"].nunique())
        detail = "; ".join(
            f"{r.column}: {r.check}" for r in e.failure_cases.head(3).itertuples()
        )
        sample = e.failure_cases.head(5).astype(str).to_dict(orient="records")
    results.append(
        CheckResult(
            "structural schema (pandera)",
            "validity",
            "transactions",
            "BLOCKER",
            len(tx),
            failed,
            detail,
            owner="data engineering",
            sample=sample,
        )
    )
    return results


def check_completeness(frames: dict[str, pd.DataFrame]) -> CheckResult:
    """Customer attributes null because the customer id has no master record."""
    tx = frames["transactions"]
    nulls = tx[["cust_signup_ts", "cust_channel", "cust_region"]].isna().any(axis=1)
    orphan_cust = tx.loc[nulls, "customer_id"].nunique()
    detail = (
        f"{int(nulls.sum())} line rows arrived with null signup/channel/region - "
        f"{orphan_cust} customer ids have no master record (orphan references "
        "surfacing as missing attributes after denormalization)"
        if nulls.any()
        else "every line carries full customer attributes"
    )
    return CheckResult(
        "customer attributes present",
        "completeness",
        "transactions",
        "BLOCKER",
        len(tx),
        int(nulls.sum()),
        detail,
        owner="customer-data steward",
        sample=tx.loc[nulls, ["txn_id", "customer_id"]]
        .head(5)
        .astype(str)
        .to_dict("records"),
    )


def check_validity_categories(frames: dict[str, pd.DataFrame]) -> CheckResult:
    tx = frames["transactions"]
    bad = ~tx.category_raw.isin(CANON_CATEGORIES)
